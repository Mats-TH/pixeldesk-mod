export const dictionaries: Record<Language, Record<TextKey, string>> = { fr, en }

/** A key that comes as a pair, named without its `.one` or `.other`. */
export type PluralKey = { [K in TextKey]: K extends `${infer Base}.one` ? Base : never }[TextKey]

type Values = Readonly<Record<string, string | number>>

// French until something settles the language: nothing draws that early in a session.
let current: Language = 'fr'

export const setLanguage = (language: Language) => {
  current = language
}

export const getLanguage = () => current

const filled = (text: string, values: Values) =>
  text.replace(/\{(\w+)\}/g, (hole, name: string) => String(name === 'brand' ? BRAND : values[name] ?? hole))

/** The text under `key` in the current language, `{name}` holes filled from `values`. */
export const t = (key: TextKey, values: Values = {}) => filled(dictionaries[current][key], values)

/** Which of the two pairs: French counts from 0, English from the plural onwards. */
const form = (count: number) => (count === 1 || (current === 'fr' && count === 0) ? 'one' : 'other')

/** The variant of `key` for `count`. */
export const plural = (key: PluralKey, count: number, values: Values = {}) => t(`${key}.${form(count)}` as TextKey, values)

/** Where the two languages decide a pair on different numbers. */
export const decides = (french: number, english: number) => (current === 'fr' ? french : english)
